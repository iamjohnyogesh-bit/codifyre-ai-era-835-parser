JS = """
const b=document.body,t=document.getElementById('theme-toggle');
function get(){try{return localStorage.getItem('codifyre-theme')}catch(e){return null}}
function put(v){try{localStorage.setItem('codifyre-theme',v)}catch(e){}}
function lbl(){t.textContent=b.classList.contains('light')?'\\u263E Dark':'\\u2600 Light'}
if(get()==='light')b.classList.add('light');
lbl();
t.addEventListener('click',function(){b.classList.toggle('light');put(b.classList.contains('light')?'light':'dark');lbl()});
"""


def render(payload):
    s = payload["summary"]
    recon = payload["reconciliation"]
    kpis = [("Payments", s["payments"]), ("Claims", s["claims"]),
            ("Charged", money(s["total_charged"])), ("Paid", money(s["total_paid"])),
            ("Denial rate", f"{s['denial_rate_pct']}%"), ("Adjustments", money(s["total_adjustments"]))]
    kpi_html = "".join(f"<div class='card kpi'><span class='muted'>{esc(k)}</span><b>{esc(v)}</b></div>" for k, v in kpis)
    reasons = [{"label": f"{r['code']} {r['reason_desc'][:26]}", "amount": r["amount"]} for r in s["by_reason"][:8]]
    status = [{"label": r["status"][:30], "count": r["count"]} for r in s["by_status"]]
    payers = [{"label": r["payer"][:30], "amount": r["amount"]} for r in s["by_payer"]]
    rec_rows = "".join(
        f"<tr><td>{esc(r['payer'])}</td><td>{money(r['payment_amount'])}</td><td>{money(r['expected'])}</td>"
        f"<td class='{'ok' if r['balanced'] else 'bad'}'>{'Balanced' if r['balanced'] else 'Off ' + format(r['difference'], '+.2f')}</td></tr>"
        for r in recon)
    return f"""<!DOCTYPE html><html lang="en"><head><meta charset="utf-8">
<title>Codifyre AI - ERA 835 Dashboard</title><meta name="viewport" content="width=device-width,initial-scale=1">
<style>{CSS}</style></head><body>
<header><h1>Codifyre AI &middot; ERA 835 Parser</h1><button id="theme-toggle" type="button">Light</button></header>
<main><section class="kpis">{kpi_html}</section>
<section class="card"><h2>Adjustments by reason</h2>{bars(reasons, 'label', 'amount', money)}</section>
<section class="card"><h2>Claims by status</h2>{bars(status, 'label', 'count')}</section>
<section class="card"><h2>Payments by payer</h2>{bars(payers, 'label', 'amount', money)}</section>
<section class="card"><h2>Payment reconciliation</h2><table><tr><th>Payer</th><th>BPR</th><th>Expected</th><th>Result</th></tr>{rec_rows}</table></section>
</main><footer>Generated by Codifyre AI ERA 835 Parser. Synthetic sample data.</footer>
<script>{JS}</script></body></html>"""
