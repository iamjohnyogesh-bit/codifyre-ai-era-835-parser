"""Self-contained HTML dashboard (dark default, light toggle) for parsed 835 data."""

import html


def esc(s):
    return html.escape(str(s))


def money(v):
    return f"${v:,.2f}"


def bars(rows, label, value, fmt=str):
    if not rows:
        return "<p class='muted'>No data</p>"
    top = max(r[value] for r in rows) or 1
    out = []
    for r in rows:
        w = max(2, int(100 * r[value] / top))
        out.append(f"<div class='bar'><span class='lbl'>{esc(r[label])}</span>"
                   f"<span class='track'><i style='width:{w}%'></i></span>"
                   f"<span class='val'>{esc(fmt(r[value]))}</span></div>")
    return "".join(out)


